/** Report-period spend for campaign selection; rolling chart rows are not its default scope. */
import type { NreRow } from "./columns";
import { CAMPAIGN_SELECTION_POLICY, extractCampaignNames, extractCampaignSpend, resolveCampaignSelection, type CampaignSelectionMemory } from "./campaigns";
import { filterNreRowsByDateRange, type DateRangeIso } from "./date-range";
import { alignCsvComparison, alignCsvSelection, completeCsvBounds, csvReportNow } from "./csv-reporting-calendar";
import { resolveDateSelection } from "./resolve-date-selection";
import { historicalPeriods, selectedSinglePeriod } from "./report-period-selection";
import type { MetaApiReportSelection } from "./meta-api-import-range";

export function campaignSelectionSpend(rows: NreRow[], selection: MetaApiReportSelection, timezone: string, now = new Date(), memory: CampaignSelectionMemory | null = null) {
  const bounds = completeCsvBounds(rows, now, timezone);
  const clock = csvReportNow(rows, now, timezone);
  const dates = alignCsvSelection(selection.dateSelection, bounds, selection.reportType ?? "WEEKLY", now, timezone);
  let ranges: DateRangeIso[];
  if (selection.reportType === "COMPARISON") {
    if (!selection.comparisonPeriodA || !selection.comparisonPeriodB) throw new Error("Choose both comparison periods.");
    const aligned = alignCsvComparison(selection.comparisonPeriodA, selection.comparisonPeriodB, bounds, now, timezone);
    ranges = [aligned.periodA, aligned.periodB];
  } else if (selection.reportType === "HISTORICAL") {
    if (dates?.mode === "custom" && dates.customStart && dates.customEnd) ranges = [{startIso:dates.customStart,endIso:dates.customEnd}];
    else ranges = historicalPeriods(selection.historicalMonthCount ?? 1, undefined, false, clock, timezone);
  } else if (selection.reportType === "MONTHLY" || selection.reportType === "DAILY") {
    ranges = [selectedSinglePeriod(selection.reportType, dates, clock, timezone)!];
  } else {
    const resolved = resolveDateSelection(rows, dates ?? {mode:"last7"}, now, timezone);
    if (!resolved.ok || !resolved.weeklyRange) throw new Error(resolved.error ?? "Choose valid reporting dates.");
    ranges = [resolved.weeklyRange];
  }
  const names = extractCampaignNames(rows);
  const includedRows = new Set(ranges.flatMap(range => filterNreRowsByDateRange(rows, range)));
  const campaignSpend = { ...Object.fromEntries(names.map(name => [name, 0])), ...extractCampaignSpend([...includedRows]) };
  const periodSpend = ranges.map(range => extractCampaignSpend(filterNreRowsByDateRange(rows, range)));
  const spending = new Set(names.filter(name => periodSpend.some(spend => (spend[name] ?? 0) > 0)));
  // Legacy exclusions may have been generated by the former $10 rule.
  // Rebuild those defaults once; preserve explicit exclusions saved under this policy.
  const base = resolveCampaignSelection(names, memory?.policy === CAMPAIGN_SELECTION_POLICY ? memory : null);
  return {
    campaignSpend,
    selectedCampaigns: base.selectedCampaigns.filter(name => spending.has(name)),
    zeroSpendCampaigns: names.filter(name => periodSpend.every(spend => (spend[name] ?? 0) === 0)),
    campaignStepMode: base.stepMode,
    campaignSpendLabel: ranges.length > 1 ? "Spend across both selected periods" : `Reporting-period spend · ${ranges[0].startIso} – ${ranges[0].endIso}`,
    ranges,
  };
}
