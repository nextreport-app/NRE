import type { MetricFormat } from "./meta-dictionary";

export type GoogleDictMetricType = "dimension" | "metadata" | "primary" | "secondary" | "never";

export interface GoogleMetricDefinition {
  /** Exact lowercase CSV column header this entry matches. */
  csvName: string;
  /** Internal identifier — shared across csvName variants of the same underlying metric. */
  key: string;
  /** Display label for the PPT card. Present on primary/secondary entries only. */
  label?: string;
  type: GoogleDictMetricType;
  format?: MetricFormat;
  /** Objective keys (see detect-objective.ts) this metric is relevant for. Empty/omitted = all objectives. */
  objectives?: string[];
  /** 1-100, higher shown first. Present on primary/secondary entries only. */
  priority?: number;
  /** One-line legend explanation. Present on primary/secondary entries only. */
  explanation?: string;
  /** See MetaMetricDefinition.perUnitOf — same "never sum a per-unit cost" fix, Google's own key vocabulary. */
  perUnitOf?: string;
  /** See MetaMetricDefinition.perUnitScale. */
  perUnitScale?: number;
}

