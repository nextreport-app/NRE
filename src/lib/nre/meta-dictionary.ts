/**
 * Comprehensive Meta Ads metric dictionary — every column NextReport
 * recognizes for the dynamic metric-selection system (Metric Preview wizard
 * step + dynamic PPT card generation). This is a parallel, additive system:
 * it does not replace or interact with columns.ts's small fixed-field
 * detection (which still drives the always-on Combined Total table, MTD
 * chart, and health score) or objective.ts's OBJECTIVE_CATALOG (which still
 * drives per-row result-type labeling for those same untouched features).
 *
 * `type` meaning:
 *  - 'dimension'/'metadata': structural columns, never shown as a metric card.
 *  - 'never': real Meta columns that exist but are never useful as a report
 *    metric (internal quality rankings, invalid-traffic counts, etc).
 *  - 'primary': always included by the metric selector when present,
 *    regardless of detected objective.
 *  - 'secondary': included by the metric selector only when relevant to the
 *    detected objective (empty `objectives` = relevant to every objective).
 *
 * Multiple entries may share the same `key` (e.g. "amount spent" and "amount
 * spent (usd)" both resolve to `spend`) — CSVs vary in exact header text
 * across accounts/currencies, so each real-world column name gets its own
 * entry, keyed by the value it actually maps to.
 */

export type MetaMetricType = "dimension" | "metadata" | "primary" | "secondary" | "never";
export type MetricFormat = "currency" | "number" | "percentage" | "duration" | "ratio" | "text";

export interface MetaMetricDefinition {
  /** Exact lowercase CSV column header this entry matches. */
  csvName: string;
  /** Internal identifier — shared across csvName variants of the same underlying metric. */
  key: string;
  /** Display label for the PPT card. Present on primary/secondary entries only. */
  label?: string;
  type: MetaMetricType;
  format?: MetricFormat;
  /** Objective keys (see detect-objective.ts) this metric is relevant for. Empty/omitted = all objectives. */
  objectives?: string[];
  /** 1-100, higher shown first. Present on primary/secondary entries only. */
  priority?: number;
  /** One-line legend explanation. Present on primary/secondary entries only. */
  explanation?: string;
  /**
   * For a per-unit currency metric (a "cost per X" or "CPC/CPM"-style
   * average) that must NEVER be summed across rows: the `key` of the metric
   * whose raw values, summed across the same rows, are the denominator —
   * dynamic-metrics.ts recomputes this entry as
   * sum(spend) / sum(<perUnitOf column>) instead of summing the metric's own
   * column. The special value "__avg__" means "average the metric's own
   * non-zero raw values instead" (for a fixed bid target like Target CPA,
   * which isn't actually derived from spend/count at all). Omitted for
   * genuine aggregate currency totals (spend, revenue, conv. value, ...),
   * which keep the default sum behavior.
   */
  perUnitOf?: string;
  /** Multiplier applied to the perUnitOf division — 1000 for "cost per 1,000 X" metrics (CPM, cost per 1K reached). Defaults to 1. */
  perUnitScale?: number;
}

